import * as path from 'node:path';
import * as fs from 'fs-extra';
import { compare, validate } from 'compare-versions';

/** Environment variable that asks ExTester to launch VS Code without ever showing its window. */
export const HIDDEN_WINDOW_ENV = 'EXTESTER_HIDDEN_WINDOW';

/** First VS Code release with the `--hidden-window` CLI flag (microsoft/vscode#344174). */
export const HIDDEN_WINDOW_MIN_VERSION = '1.147.0';

/** Folder name, inside the storage folder, of the generated extension host stub. */
const HOST_FOLDER = 'hidden-window-host';

/**
 * Whether the hidden window mode was requested, via `--hidden_window`,
 * `run.hiddenWindow` in extester.config.json, or `EXTESTER_HIDDEN_WINDOW=true`.
 */
export function isHiddenWindowRequested(env: NodeJS.ProcessEnv = process.env): boolean {
	const value = env[HIDDEN_WINDOW_ENV]?.trim().toLowerCase();
	return value === 'true' || value === '1';
}

/**
 * Whether the given VS Code version knows `--hidden-window`. A version that cannot be
 * parsed (e.g. a custom build) is treated as unsupported: the hidden window mode also
 * runs VS Code in extension test mode, which an older build would get without the
 * hidden window.
 */
export function supportsHiddenWindow(codeVersion: string): boolean {
	const version = codeVersion.replace(/-insider$/, '');
	return validate(version) && compare(version, HIDDEN_WINDOW_MIN_VERSION, '>=');
}

/**
 * Launch arguments that keep the VS Code window hidden for the whole session.
 *
 * VS Code honours `--hidden-window` only while it runs extension tests, i.e. together
 * with `--extensionTestsPath` (which itself needs an `--extensionDevelopmentPath`), and
 * it exits as soon as that test runner settles. ExTester drives VS Code from the outside,
 * so it passes a generated runner whose `run()` never settles: VS Code stays up until
 * ExTester quits it, exactly as in a normal run.
 *
 * @param storagePath ExTester storage folder, where the runner stub is generated
 * @param hasExtensionDevPath whether the launch already carries an `--extensionDevelopmentPath`
 */
export function hiddenWindowArgs(storagePath: string, hasExtensionDevPath: boolean): string[] {
	const hostDir = writeHiddenWindowHost(storagePath);
	const args = ['--hidden-window', `--extensionTestsPath=${path.join(hostDir, 'keepalive.js')}`];
	if (!hasExtensionDevPath) {
		args.push(`--extensionDevelopmentPath=${hostDir}`);
	}
	return args;
}

/**
 * Write a manifest-only extension whose folder doubles as the development path and
 * holds the never-settling test runner.
 */
function writeHiddenWindowHost(storagePath: string): string {
	const hostDir = path.join(storagePath, HOST_FOLDER);
	fs.mkdirpSync(hostDir);
	fs.writeJSONSync(
		path.join(hostDir, 'package.json'),
		{
			name: 'extester-hidden-window-host',
			displayName: 'ExTester hidden window host',
			description: 'Keeps a hidden VS Code window open while ExTester drives it.',
			publisher: 'redhat',
			version: '0.0.1',
			engines: { vscode: `^${HIDDEN_WINDOW_MIN_VERSION}` },
		},
		{ spaces: '\t' },
	);
	fs.writeFileSync(
		path.join(hostDir, 'keepalive.js'),
		[
			'// Generated by ExTester for --hidden_window. VS Code exits once an extension test',
			'// runner settles; ExTester drives the UI from outside, so this one never does.',
			'exports.run = () => new Promise(() => {});',
			'',
		].join('\n'),
	);
	return hostDir;
}

/** The parts of a selenium `WebDriver` that a hidden window restart moves to another object. */
interface SessionHolder {
	getSession(): Promise<{ getId(): string }>;
	getExecutor(): CommandExecutor;
}

interface CommandExecutor {
	execute(command: { setParameter(name: string, value: unknown): unknown }): Promise<unknown>;
}

/** Private `WebDriver` fields that hold a session: the session, the command executor and the quit hook (which stops the matching ChromeDriver). */
const SESSION_FIELDS = ['session_', 'executor_', 'onQuit_'];

/**
 * Point `target` at the session of `source`. Selenium has no public API for this, so it
 * moves the private fields that hold the session, and fails clearly if a selenium-webdriver
 * release no longer has them.
 */
export function adoptSession(target: object, source: object): void {
	const to = target as Record<string, unknown>;
	const from = source as Record<string, unknown>;
	const missing = SESSION_FIELDS.filter((field) => !(field in from) || !(field in to));
	if (missing.length > 0) {
		throw new Error(
			`Hidden window: cannot move the WebDriver session to the restarted VS Code, this selenium-webdriver version has no ${missing.join(', ')} field. Please report it to ExTester.`,
		);
	}
	for (const field of SESSION_FIELDS) {
		to[field] = from[field];
	}
	// The CDP connection of the previous session was closed by its quit(); a new one is opened on demand.
	to._cdpWsConnection = undefined;
	to._cdpConnection = undefined;
}

/**
 * Close the BiDi connection selenium keeps for `driver`. `WebDriver.quit()` skips this when a
 * quit hook is set (as it is for ChromeDriver), so after a restart the driver would get the dead
 * connection of the previous session back. Best effort: the module is internal to selenium.
 */
export async function closeBidiConnection(driver: object): Promise<void> {
	try {
		const bidi = require('selenium-webdriver/lib/bidi_connection') as { closeBidiConnection?: (driver: object) => Promise<void> };
		await bidi.closeBidiConnection?.(driver);
	} catch {
		// no BiDi connection was open, or this selenium-webdriver version keeps it elsewhere
	}
}

/**
 * After a restart, send commands that still reach the executor of a closed session to the
 * current session of `driver`. `WebDriver.execute()` reads the session id before it awaits the
 * command parameters and only then reads the executor, so a command sent while the restart
 * runs carries the id of the closed session, and one whose request had already started uses
 * the old executor; without this they would fail with ECONNREFUSED or an invalid session id.
 */
export function forwardToCurrentSession(previous: CommandExecutor, driver: SessionHolder): void {
	previous.execute = async (command) => {
		const current = driver.getExecutor();
		if (current === previous) {
			throw new Error('Hidden window: the WebDriver session was closed');
		}
		command.setParameter('sessionId', (await driver.getSession()).getId());
		return await current.execute(command);
	};
}

/** What the window has open, as far as ExTester opened it: a hidden window reload opens it again. */
export interface OpenedResources {
	/** absolute paths of the folders or `.code-workspace` file the window has open */
	workspace: string[];
	/** absolute paths of the files opened through ExTester, least recently opened first */
	files: string[];
}

/**
 * Record resources that were opened. A folder or workspace replaces the previous one and closes its
 * editors; a file opened again moves to the end, as the most recently opened one.
 */
export function trackOpened(state: OpenedResources, resources: string[], isWorkspace: (resource: string) => boolean): OpenedResources {
	const resolved = resources.map((resource) => path.resolve(resource));
	const workspace = resolved.filter(isWorkspace);
	let files = workspace.length > 0 ? [] : state.files;
	for (const file of resolved.filter((resource) => !isWorkspace(resource))) {
		files = [...files.filter((known) => known !== file), file];
	}
	return { workspace: workspace.length > 0 ? workspace : state.workspace, files };
}

/**
 * Files to open again after a hidden window reload: those opened through ExTester whose editor is still
 * open (exact title match) and that still exist. The active editor's file comes last, so VS Code
 * focuses it again; the others keep their opening order.
 */
export function filesToReopen(
	openedFiles: string[],
	editorTitles: string[],
	activeTitle: string | undefined,
	exists: (file: string) => boolean = fs.existsSync,
): string[] {
	const files = openedFiles.filter((file) => exists(file) && editorTitles.includes(path.basename(file)));
	const isActive = (file: string) => path.basename(file) === activeTitle;
	return [...files.filter((file) => !isActive(file)), ...files.filter(isActive)];
}
